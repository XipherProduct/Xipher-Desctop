// Поиск: матчится английское имя, русские ключевые слова и сам символ.
inline bool matches(const QString& emoji, const QString& query) {
    const QString q = query.trimmed().toLower();
    if (q.isEmpty()) return true;
    const QString hay = en().value(emoji) + QLatin1Char(' ') + ru().value(emoji)
                        + QLatin1Char(' ') + emoji;
    return hay.toLower().contains(q);
}

